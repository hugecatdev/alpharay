def schedule_html(schedule: list[Payment]) -> str:
    rows = "".join(
        f"<tr><td>{index}</td><td>{date_ru(row.date)}</td><td>{money(row.amount)}</td>"
        f"<td>{money(row.principal)}</td><td>{money(row.interest)}</td><td>{money(row.balance)}</td></tr>"
        for index, row in enumerate(schedule, start=1)
    )
    total = money(sum(row.amount for row in schedule))
    principal = money(sum(row.principal for row in schedule))
    interest = money(sum(row.interest for row in schedule))
    return f"""<h3>Приложение № 1. График платежей</h3>
<table class="schedule">
<thead><tr><th>№</th><th>Дата платежа</th><th>Платёж</th><th>Основной долг</th><th>Проценты</th><th>Остаток долга</th></tr></thead>
<tbody>{rows}</tbody>
<tfoot><tr><td colspan="2">Итого</td><td>{total}</td><td>{principal}</td><td>{interest}</td><td></td></tr></tfoot>
</table>
<p class="note">Проценты в графике рассчитаны исходя из 1/12 годовой ставки за каждый процентный период. Платежи и проценты округляются до целого рубля; последний платёж погашает остаток основного долга и проценты за последний период. Итоговые суммы равны суммам строк графика. До предоставления Кредита даты платежей предварительные и отсчитываются от даты его предоставления.</p>"""


def contract_html(record: ApplicationRecord, now: int) -> str:
    amount, term, rate = loan_terms(record)
    company = record.company
    revolving = record.product.repayment == "REVOLVING"
    reference = record.contract.ref() if record.contract else None
    number = reference.number if reference else f"ДК-{record.number.replace('КР-', '')}"
    signed_at = reference.signed_at if reference else None
    start = schedule_start(record, now)
    title = "Договор об овердрафтном кредитовании" if revolving else "Кредитный договор"
    if revolving:
        sections = overdraft_sections(record, amount, term, rate, start)
        appendix = ""
    else:
        schedule = build_schedule(amount, term, rate, start)
        sections = loan_sections(record, amount, term, rate, start, number, schedule)
        appendix = schedule_html(schedule)
    sections += common_sections(record, revolving)
    tail = len(sections)
    body = "\n".join(
        [
            *(section(index, heading, clauses) for index, (heading, clauses) in enumerate(sections, start=1)),
            signing_section(tail + 1, company, reference),
            section(tail + 2, "Разрешение споров", DISPUTES),
            section(tail + 3, "Заключительные положения", final_clauses(revolving)),
            requisites(tail + 4, company, reference),
        ]
    )
    return f"""<article class="contract">
<h2>{title} № {escape_html(number)}</h2>
<p class="meta">г. Москва · {date_ru(signed_at or now)}</p>
<p class="meta">{DEMO_NOTE}</p>
{preamble(company)}
{body}
{appendix}
</article>"""
